"""csvstats.lmm against R on the SAMPLED scenario set.

The fixtures are in tests/reference/scenarios, generated by
make_lmm_scenarios.R: 9 random-effect structures x 25 stratified draws.
Plans: .claude/plan-lmm-scenario-generator.md,
.claude/plan-lmm-general-fit.md and .claude/plan-lmm-covariate-type3.md.
Doc: docs/claude/lmm-r-oracle-testing.md. All are in the scistack repo.

The layers, each checked wherever csv-stats can express the scenario. The
ONE owner of "can it" is :func:`route`; every skip carries its reason, and
the parity table counts them.

- objective parity: csv-stats' REML and ML criterion at R's probe theta
  (``csvstats.lmm_fit.MixedModel``). No optimizer is involved, so the
  tolerance is tight.
- optimum parity: csv-stats' optimum is at least as good as lme4's.
- theta parity: within the spread of R's own optimizers.
- inference parity through the public lmm():
  - always: fixed effects, SEs, variance components, the singular flag,
    Satterthwaite t
  - any design with a fixed term: the type-III F tests
  - any design with a factor: the emmeans contrasts (covariates at their mean)

Run with ``-s`` for the parity table.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

import numpy as np
import pandas as pd
import pytest

from _lmm_oracle import (
    INFERENCE_LOOSEN,
    LOGLIK_ATOL,
    SINGULAR_LOOSEN,
    T_RTOL,
    as_dict,
    as_list,
    assert_coefficient_satterthwaite,
    assert_fixed_effects,
    assert_pairwise_contrasts,
    assert_singular_agrees,
    assert_term_f_tests,
    assert_variance_rows,
    rel,
    stopped_short,
)
from csvstats.lmm import lmm, lmm_pairwise
from csvstats.lmm_fit import SINGULAR_TOL, MixedModel, build_blocks, parse_random

SCEN = Path(__file__).parent / "reference" / "scenarios"
MANIFEST = SCEN / "manifest.csv"
CASES = sorted(p.stem for p in (SCEN / "results").glob("*.json")) if (SCEN / "results").exists() else []

#: Objective parity: the same function at the same theta, so only floating
#: point separates the two. Relative to the deviance, with an absolute floor
#: for deviances near 0.
OBJECTIVE_RTOL = 1e-8
OBJECTIVE_ATOL = 1e-6
#: csv-stats' optimum may be at most this much WORSE than lme4's criterion.
OPTIMUM_ATOL = 1e-6
#: theta: absolute, on lme4's scale (relative SDs and Cholesky factors),
#: widened to 10 x R's optimizer spread.
THETA_ATOL = 1e-4
#: How many times R's own optimizer spread a difference may be.
SPREAD_FACTOR = 10.0

#: The stratified minimums per structure (make_lmm_scenarios.R STRATA).
QUOTAS = {"balanced": 3, "zero_variance": 4, "small_n": 3, "heavy_missing": 3, "scale": 2, "collinear": 1}
CORRELATED = {"RIS", "RIF", "CROSSED_SLOPES", "RIS_FACTOR"}
PER_STRUCTURE = 25
STRUCTURES = {"RI", "RIS", "RIS_UNCORR", "RIF", "RM", "CROSSED", "NESTED", "CROSSED_SLOPES", "RIS_FACTOR"}


@lru_cache(maxsize=None)
def reference(case: str) -> dict:
    with open(SCEN / "results" / f"{case}.json") as f:
        ref = json.load(f)
    for key in ("factors", "between", "within", "covariates", "fixed_terms", "fixed_columns",
                "dropped_columns", "theta", "theta_names", "theta_lower"):
        ref[key] = as_list(ref.get(key))
    ref["levels"] = as_dict(ref.get("levels"))
    for block in ref.get("random") or []:
        block["group"] = as_list(block["group"])
        block["terms"] = as_list(block["terms"])
    return ref


@lru_cache(maxsize=None)
def data(case: str) -> pd.DataFrame:
    ref = reference(case)
    text = ["subject", "item", "site", *ref["factors"]]
    return pd.read_csv(SCEN / "datasets" / f"{case}.csv", dtype={c: str for c in text})


# --- the one owner of "what csv-stats can check today" ---------------------

@dataclass(frozen=True)
class Route:
    """How far csv-stats can follow this scenario.

    - ``objective``: :class:`MixedModel` evaluates its criterion (every
      scenario R fitted).
    - ``lmm``: kwargs for the public :func:`csvstats.lmm.lmm`, or None when
      it cannot express the model.
    - ``terms``: the type-III F tests are comparable (any design with a
      fixed term, covariates included since plan-lmm-covariate-type3).
    - ``contrasts``: the emmeans contrasts are comparable (any design with
      a factor; covariates at emmeans' reference-grid mean since
      plan-lmm-covariate-contrasts).
    - ``reason``: why it is less than the full route ("" when full).
    """

    objective: bool
    lmm: dict | None
    terms: bool
    contrasts: bool
    reason: str


def route(ref: dict) -> Route:
    if ref.get("error"):
        return Route(False, None, False, False, "R could not fit it")
    if ref.get("collinear"):
        return Route(True, None, False, False, "collinear fixed column: lmm() refuses a rank-deficient design")
    kwargs = dict(between=ref["between"], within=ref["within"], subject="subject", levels=ref["levels"],
                  covariates=ref["covariates"], random=ref["random"])
    if not ref["factors"] and not ref["covariates"]:
        return Route(True, kwargs, False, False, "intercept-only fixed design: no term tests")
    if not ref["factors"]:
        return Route(True, kwargs, True, False, "no factor: no pairwise contrasts")
    return Route(True, kwargs, True, True, "")


def _route(case: str) -> Route:
    return route(reference(case))


def _need_objective(case: str) -> dict:
    r = _route(case)
    if not r.objective:
        pytest.skip(r.reason)
    return reference(case)


def _need_lmm(case: str) -> dict:
    r = _route(case)
    if r.lmm is None:
        pytest.skip(r.reason)
    return reference(case)


def _need_terms(case: str) -> dict:
    r = _route(case)
    if not r.terms:
        pytest.skip(r.reason)
    return reference(case)


def _need_contrasts(case: str) -> dict:
    r = _route(case)
    if not r.contrasts:
        pytest.skip(r.reason)
    return reference(case)


# --- csv-stats' side ----------------------------------------------------------

def design(case: str) -> np.ndarray:
    """The fixed-effect design matrix lme4 used, rebuilt with patsy from the
    language-neutral ``fixed_terms``. Sum coding in the recorded level order
    gives lme4's columns (up to order, which no criterion depends on); the
    columns lme4 dropped as collinear are dropped by name."""
    import patsy

    ref = reference(case)
    frame = data(case).copy()
    numeric = set(ref["covariates"]) | ({ref["collinear"]} if ref.get("collinear") else set())
    for f in ref["factors"]:
        frame[f] = pd.Categorical(frame[f], categories=ref["levels"][f])

    def piece(name: str) -> str:
        return name if name in numeric else f"C({name}, Sum)"

    rhs = " + ".join(":".join(piece(p) for p in term.split(":")) for term in ref["fixed_terms"]) or "1"
    X = patsy.dmatrix(rhs, frame, return_type="dataframe")
    unknown = [c for c in ref["dropped_columns"] if c not in X.columns]
    assert not unknown, f"lme4 dropped {unknown}, which patsy names differently: map them here"
    X = X.drop(columns=ref["dropped_columns"])
    # fixed_columns is lme4's X AFTER dropping.
    assert X.shape[1] == len(ref["fixed_columns"]), f"patsy {list(X.columns)} vs lme4 {ref['fixed_columns']}"
    return X.to_numpy(float)


@lru_cache(maxsize=None)
def model(case: str, reml: bool = True) -> MixedModel:
    ref = reference(case)
    frame = data(case)
    blocks = build_blocks(frame, parse_random(ref["random"], "subject"), ref["levels"])
    return MixedModel(design(case), frame["y"].to_numpy(float), blocks, reml=reml)


def to_ours(case: str, r_theta) -> np.ndarray:
    """R's theta vector in csv-stats' order. Matched by name when both sides
    name every theta uniquely and the names agree as sets (a different
    block ORDER is then harmless); otherwise by position."""
    m = model(case)
    r_theta = np.asarray(as_list(r_theta), dtype=float)
    r_names = reference(case)["theta_names"]
    ours = m.theta_names
    if len(r_names) == len(ours) and len(set(r_names)) == len(r_names) and set(r_names) == set(ours):
        index = {n: i for i, n in enumerate(r_names)}
        return r_theta[[index[n] for n in ours]]
    return r_theta


def test_theta_names_and_order_match_lme4():
    """csv-stats lays theta out as lme4 does: same names, same order (the
    block-order convention). A name difference only affects how theta is
    matched in to_ours; an ORDER difference means lme4_order is wrong."""
    checked = 0
    for case in CASES:
        if not _route(case).objective:
            continue
        r_names = reference(case)["theta_names"]
        if len(set(r_names)) != len(r_names):
            continue  # lme4 repeated a name (|| blocks): order checked by position elsewhere
        ours = model(case).theta_names
        if set(ours) == set(r_names):
            assert ours == r_names, f"{case}: block order {ours} vs lme4 {r_names}"
            checked += 1
    if CASES:
        assert checked > 0, "no scenario had comparable theta names"


@lru_cache(maxsize=None)
def our_fit(case: str):
    return model(case).fit()


@lru_cache(maxsize=None)
def fit(case: str) -> dict:
    return lmm(data(case), "y", **_route(case).lmm)


@lru_cache(maxsize=None)
def pairwise(case: str, factor: str) -> dict:
    return lmm_pairwise(data(case), "y", factor=factor, **_route(case).lmm)


# --- tolerances from R's own optimizers ---------------------------------------

def spread(ref: dict) -> dict:
    return (ref.get("optimizers") or {}).get("spread") or {}


def lme4_stopped_short(case: str) -> bool:
    return stopped_short(our_fit(case).loglik, reference(case)["loglik_reml"])


def _scale(case: str) -> float:
    return float(data(case)["y"].std())


def _loosen(ref: dict) -> float:
    return SINGULAR_LOOSEN if ref.get("singular") else 1.0


def _inference_loosen(case: str) -> float:
    """INFERENCE_LOOSEN on a singular fit or where lme4 stopped short; and
    never tighter than SPREAD_FACTOR x the t that R's own optimizers
    disagree on. A t is est / SE, so it cannot be pinned tighter than the
    estimate and SE are: lme4's optimizers at one optimum still differ by
    ~1e-4 in theta on several-theta fits (NESTED_006, RM_024, 2026-10-20).
    Only optimizers AT the optimum count (_at_optimum): one that stopped at
    a worse criterion would loosen the check to nothing (RIF_020's bobyqa)."""
    ref = reference(case)
    base = INFERENCE_LOOSEN if ref.get("singular") or lme4_stopped_short(case) else 1.0
    fits = _at_optimum(ref)
    t_spread = 0.0
    for r in ref["fixed"]:
        ts = [f["fixef"][r["name"]] / f["se"][r["name"]] for f in fits
              if f.get("se", {}).get(r["name"]) and r["name"] in f.get("fixef", {})]
        if len(ts) > 1:
            t_spread = max(t_spread, (max(ts) - min(ts)) / max(abs(r.get("t") or 0.0), 1.0))
    return max(base, SPREAD_FACTOR * t_spread / T_RTOL)


def _at_optimum(ref: dict) -> list[dict]:
    """R's converged optimizer fits within 2 x LOGLIK_ATOL of the best criterion."""
    fits = [f for f in as_list((ref.get("optimizers") or {}).get("fits")) if f.get("ok") and f.get("converged")]
    if not fits:
        return []
    best = min(f["criterion"] for f in fits)
    return [f for f in fits if f["criterion"] <= best + 2 * LOGLIK_ATOL]


def _r_singularity_ambiguous(ref: dict) -> bool:
    """R's own optimizers reach the same optimum (criteria within
    2 x LOGLIK_ATOL) but disagree on isSingular: the optimum sits within
    reach of the 1e-4 threshold (RIF_020: Nelder_Mead theta 3.5e-5,
    nlopt_bobyqa 1.7e-4, criteria 2e-7 apart)."""
    diag = [i for i, low in enumerate(as_list(ref.get("theta_lower"))) if low == 0]
    flags = {any(as_list(f["theta"])[i] < SINGULAR_TOL for i in diag) for f in _at_optimum(ref)}
    return len(flags) > 1


def _floors(ref: dict) -> dict:
    s = spread(ref)
    return {key: {name: SPREAD_FACTOR * float(v) for name, v in as_dict(s.get(key)).items()}
            for key in ("fixef", "se")}


def _variance_floors(ref: dict) -> list[float]:
    """Per R VarCorr row: 10 x the spread of that row's vcov over R's optimizers."""
    return [SPREAD_FACTOR * float(v) for v in as_list(spread(ref).get("vcov"))]


# --- the set itself -----------------------------------------------------------

def test_the_scenario_set_is_present():
    """The manifest and every scenario's two files exist."""
    assert MANIFEST.exists(), "run tests/reference/make_lmm_scenarios.R (see tests/reference/README.md)"
    manifest = pd.read_csv(MANIFEST)
    assert sorted(manifest["id"]) == CASES, "manifest and results/ disagree: rerun the script"
    assert len(CASES) == len(STRUCTURES) * PER_STRUCTURE
    for case in CASES:
        assert (SCEN / "datasets" / f"{case}.csv").exists(), case


def test_coverage_quotas():
    """A regeneration can't silently lose the hard cases: every structure
    has its stratified minimums, R fitted nearly everything, and singular
    fits are present."""
    if not MANIFEST.exists():
        pytest.skip("no manifest (test_the_scenario_set_is_present says how to make it)")
    m = pd.read_csv(MANIFEST)
    assert set(m["structure"]) == STRUCTURES
    for structure, rows in m.groupby("structure"):
        assert len(rows) == PER_STRUCTURE, structure
        counts = rows["stratum"].value_counts()
        for stratum, need in QUOTAS.items():
            assert counts.get(stratum, 0) >= need, f"{structure}: {stratum} {counts.get(stratum, 0)} < {need}"
        if structure in CORRELATED:
            assert counts.get("corr_boundary", 0) >= 3, f"{structure}: corr_boundary"
            assert (rows["true_max_abs_corr"] >= 0.97).sum() >= 3, f"{structure}: true |corr| >= 0.97"
        assert rows["true_zero_variance"].sum() >= QUOTAS["zero_variance"], f"{structure}: true zero variances"
        small = rows.loc[rows["stratum"] == "small_n", "n_subjects"].tolist()
        assert (rows["n_subjects"] <= 8).sum() >= QUOTAS["small_n"], f"{structure}: n <= 8 (small_n stratum drew {small})"
    failed = m[m["verdict"] == "failed"]
    assert len(failed) <= 0.05 * len(m), f"R failed on {list(failed['id'])}"
    assert m["singular"].fillna(False).astype(bool).sum() >= 8, "fewer than 8 singular fits"
    collinear = m[m["collinear"].astype(bool)]
    assert len(collinear) >= len(STRUCTURES), "collinear scenarios"
    fitted = collinear[collinear["verdict"] != "failed"]
    assert (fitted["n_dropped"] >= 1).all(), f"lme4 dropped no column for z: {list(fitted['id'][fitted['n_dropped'] < 1])}"


# --- objective and optimum ----------------------------------------------------

@pytest.mark.parametrize("case", CASES)
def test_objective_matches_lme4_at_probe_theta(case):
    """csv-stats' REML and ML deviance equal lme4's devFunOnly at every probe
    theta: the estimate, +-10% steps, the boundary, three random points."""
    ref = _need_objective(case)
    reml, ml = model(case, True), model(case, False)
    for probe in ref["probes"]:
        theta = to_ours(case, probe["theta"])
        assert reml.deviance(theta) == pytest.approx(probe["reml"], rel=OBJECTIVE_RTOL, abs=OBJECTIVE_ATOL), \
            f"REML at {probe['label']} (theta={theta.tolist()})"
        assert ml.deviance(theta) == pytest.approx(probe["ml"], rel=OBJECTIVE_RTOL, abs=OBJECTIVE_ATOL), \
            f"ML at {probe['label']} (theta={theta.tolist()})"


@pytest.mark.parametrize("case", CASES)
def test_optimum_is_at_least_as_good_as_lme4(case):
    """csv-stats' REML criterion at its optimum is no worse than lme4's. A
    better one means lme4 stopped short (counted below)."""
    ref = _need_objective(case)
    ours = our_fit(case).criterion
    assert ours <= ref["reml_criterion"] + OPTIMUM_ATOL, \
        f"csv-stats {ours} vs lme4 {ref['reml_criterion']} ({our_fit(case).optimizer_path})"


def test_lme4_stopping_short_is_rare():
    """If csv-stats beats lme4 often, csv-stats' criterion probably changed."""
    usable = [c for c in CASES if _route(c).objective]
    short = [c for c in usable if lme4_stopped_short(c) and
             our_fit(c).loglik - reference(c)["loglik_reml"] > LOGLIK_ATOL]
    assert len(short) <= max(3, 0.05 * len(usable)), short


@pytest.mark.parametrize("case", CASES)
def test_theta_matches_lme4(case):
    ref = _need_objective(case)
    ours = np.asarray(our_fit(case).theta, dtype=float)
    theirs = to_ours(case, ref["theta"])
    floors = SPREAD_FACTOR * to_ours(case, as_list(spread(ref).get("theta")) or [0.0] * len(theirs))
    tol = np.maximum(THETA_ATOL * _loosen(ref), floors)
    if lme4_stopped_short(case):
        tol = tol * INFERENCE_LOOSEN
    bad = [(n, o, t, tl) for n, o, t, tl in zip(model(case).theta_names, ours, theirs, tol) if abs(o - t) > tl]
    assert not bad, f"theta (name, csv-stats, lme4, tol): {bad}"


