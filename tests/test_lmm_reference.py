"""csvstats.lmm against R (lme4 / lmerTest), scenario by scenario.

Stage 2 of .claude/plan-lmm-satterthwaite.md: FIT PARITY. Satterthwaite
degrees of freedom are computed from the fitted model, so they can only match
lmerTest if the fit itself matches lme4: the fixed effects, their standard
errors, the variance components and the REML log-likelihood. This file
checks that, for every dataset in tests/reference (generated by
make_lmm_reference.R), before any df work.

The tolerances and comparisons are shared with test_lmm_scenarios.py (the
sampled set) in _lmm_oracle.py.

Run with ``-s`` to see the parity table: the largest relative error per
scenario, so accuracy is visible, not just pass/fail.
"""

from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path

import numpy as np
import pandas as pd
import pytest

from _lmm_oracle import (
    INFERENCE_LOOSEN,
    LOGLIK_ATOL,
    SINGULAR_LOOSEN,
    as_list,
    assert_coefficient_satterthwaite,
    assert_fixed_effects,
    assert_pairwise_contrasts,
    assert_pairwise_wald,
    assert_singular_agrees,
    assert_term_f_tests,
    assert_variance_components,
    assert_wald_alongside,
    r_variances,
    rel,
    stopped_short,
)
from csvstats.lmm import lmm, lmm_pairwise

REF = Path(__file__).parent / "reference"
CASES = sorted(p.stem for p in (REF / "results").glob("*.json"))


@lru_cache(maxsize=None)
def reference(case: str) -> dict:
    with open(REF / "results" / f"{case}.json") as f:
        ref = json.load(f)
    for key in ("factors", "between", "within"):
        ref[key] = as_list(ref.get(key))
    return ref


@lru_cache(maxsize=None)
def data(case: str) -> pd.DataFrame:
    ref = reference(case)
    return pd.read_csv(REF / "datasets" / f"{case}.csv", dtype={f: str for f in ["subject", *ref["factors"]]})


@lru_cache(maxsize=None)
def fit(case: str) -> dict:
    ref = reference(case)
    return lmm(data(case), "y", between=ref["between"], within=ref["within"], subject="subject",
               levels=ref["levels"])


def _skip_reason(case: str) -> str | None:
    ref = reference(case)
    if ref["scenario"].get("future"):
        return "random slopes: future scope (csv-stats fits intercept-only models)"
    if ref.get("error"):
        return f"R could not fit it: {ref['error']}"
    return None


def _usable(case: str) -> dict:
    reason = _skip_reason(case)
    if reason:
        pytest.skip(reason)
    return reference(case)


def _scale(case: str) -> float:
    return float(data(case)["y"].std())


def _loosen(ref: dict) -> float:
    return SINGULAR_LOOSEN if ref.get("singular") else 1.0


def lme4_stopped_short(case: str) -> bool:
    return stopped_short(fit(case)["details"]["log_likelihood"], reference(case)["loglik_reml"])


def _inference_loosen(case: str) -> float:
    ref = reference(case)
    return INFERENCE_LOOSEN if ref.get("singular") or lme4_stopped_short(case) else 1.0


def test_the_reference_set_is_present():
    """Every results file has its dataset, and there are enough to matter."""
    assert len(CASES) >= 70, "run tests/reference/make_lmm_reference.R"
    for case in CASES:
        assert (REF / "datasets" / f"{case}.csv").exists(), case


@pytest.mark.parametrize("case", CASES)
def test_fixed_effects_match_lme4(case):
    ref = _usable(case)
    assert_fixed_effects(fit(case)["details"]["coefficients"], ref, _scale(case), _loosen(ref))


@pytest.mark.parametrize("case", CASES)
def test_variance_components_match_lme4(case):
    ref = _usable(case)
    assert_variance_components(fit(case)["details"], ref, _scale(case), _loosen(ref))


@pytest.mark.parametrize("case", CASES)
def test_singular_fits_are_flagged_like_lme4(case):
    """lme4's isSingular and csv-stats' singular_fit warning agree, both ways."""
    assert_singular_agrees(fit(case), _usable(case))


@pytest.mark.parametrize("case", CASES)
def test_reml_log_likelihood_matches_lme4(case):
    ref = _usable(case)
    ours = fit(case)["details"]["log_likelihood"]
    assert ours == pytest.approx(ref["loglik_reml"], abs=LOGLIK_ATOL * _loosen(ref))


def test_lme4_stopping_short_is_rare():
    """The relaxation must stay an exception: if it spreads, csv-stats (not
    lme4) is probably the one that changed."""
    usable = [c for c in CASES if not _skip_reason(c)]
    short = [c for c in usable if lme4_stopped_short(c)]
    assert len(short) <= 3, short


@pytest.mark.parametrize("case", CASES)
def test_coefficient_satterthwaite_matches_lmertest(case):
    """Stage 3: every coefficient's Satterthwaite df, t and p (lmerTest's
    summary()). A fallback to Wald is allowed only with its warning, and
    then the comparison is skipped for that coefficient, never silent."""
    ref = _usable(case)
    assert_coefficient_satterthwaite(fit(case), ref, _inference_loosen(case))


@pytest.mark.parametrize("case", CASES)
def test_term_f_tests_match_lmertest_anova(case):
    """Stage 4: every term's type-III F, NumDF, DenDF (Satterthwaite,
    Fai–Cornelius) and p against lmerTest's anova(type = 3). The terms come
    in the same order and with the same names ("group:time")."""
    ref = _usable(case)
    assert_term_f_tests(fit(case), ref, _inference_loosen(case))


@pytest.mark.parametrize("case", CASES)
def test_wald_chi2_alongside_matches_r(case):
    """The Wald chi2 kept under each term's "wald" equals F * NumDF from R."""
    assert_wald_alongside(fit(case), _usable(case))


@lru_cache(maxsize=None)
def pairwise(case: str, factor: str) -> dict:
    ref = reference(case)
    return lmm_pairwise(data(case), "y", between=ref["between"], within=ref["within"], subject="subject",
                        levels=ref["levels"], factor=factor)


@pytest.mark.parametrize("case", CASES)
def test_pairwise_contrasts_match_emmeans(case):
    """Stage 5: every full-model pairwise contrast of every factor, within
    every combination of the others, against emmeans (lmer.df =
    "satterthwaite"): estimate, SE, df, t, p."""
    ref = _usable(case)
    assert_pairwise_contrasts(lambda f: pairwise(case, f), ref, _scale(case), _inference_loosen(case))


@pytest.mark.parametrize("case", CASES)
def test_pairwise_wald_alongside_matches_emmeans_asymptotic(case):
    """The Wald z kept with each contrast equals emmeans' asymptotic z."""
    ref = _usable(case)
    assert_pairwise_wald(lambda f: pairwise(case, f), ref, _inference_loosen(case))


def test_print_parity_table():
    """Not an assertion: the largest relative error per scenario (run with -s)."""
    lines = [f"{'scenario':58} {'beta':>9} {'se':>9} {'var_s':>9} {'var_e':>9} {'loglik':>9} {'df':>9} {'ddf':>9} sing"]
    for case in CASES:
        if _skip_reason(case):
            continue
        ref = reference(case)
        try:
            rec = fit(case)
        except Exception as exc:  # the parametrized tests report it properly
            lines.append(f"{case:58} ERROR {exc}")
            continue
        scale = _scale(case)
        ours = {c["name"]: c for c in rec["details"]["coefficients"]}
        beta = max((rel(ours[r["name"]]["estimate"], r["estimate"], scale) for r in ref["fixed"] if r["name"] in ours),
                   default=np.nan)
        se = max((rel(ours[r["name"]]["se"], r["se"], scale) for r in ref["fixed"] if r["name"] in ours), default=np.nan)
        subject, residual = r_variances(ref)
        var_s = rel(rec["details"]["subject_intercept_variance"], subject, scale ** 2)
        var_e = rel(rec["details"]["residual_variance"], residual, scale ** 2)
        loglik = abs(rec["details"]["log_likelihood"] - ref["loglik_reml"])
        flagged = any(w["code"] == "singular_fit" for w in rec["warnings"])
        df = max((rel(ours[r["name"]]["df"], r["df"], 1.0) for r in ref["fixed"]
                  if r["name"] in ours and ours[r["name"]]["df"] is not None and r["df"] is not None), default=np.nan)
        terms = {e["term"]: e for e in rec["effects"]}
        ddf = max((rel(terms[r["term"]]["df"][1], r["den_df"], 1.0) for r in ref["anova_satterthwaite"]
                   if r["term"] in terms and terms[r["term"]]["df_method"] == "satterthwaite"), default=np.nan)
        lines.append(f"{case:58} {beta:9.1e} {se:9.1e} {var_s:9.1e} {var_e:9.1e} {loglik:9.1e} {df:9.1e} {ddf:9.1e} "
                     f"{'R' if ref['singular'] else '-'}{'P' if flagged else '-'}")
    print("\nLMM fit parity vs lme4 (relative error; sing: R = lme4 singular, P = csv-stats flagged)")
    print("\n".join(lines))
