# --- the table ------------------------------------------------------------------

def test_print_parity_table():
    """Not an assertion: what csv-stats can check today, and the worst error
    per scenario (run with -s)."""
    if not CASES:
        print("\nno sampled scenarios: run tests/reference/make_lmm_scenarios.R")
        return
    routes = {c: _route(c) for c in CASES}
    full = sum(r.lmm is not None for r in routes.values())
    objective = sum(r.objective for r in routes.values())
    reasons = pd.Series([r.reason.split(":")[0] for r in routes.values() if r.reason]).value_counts()
    print(f"\nLMM scenario parity vs lme4: {len(CASES)} scenarios; objective-checkable {objective}; "
          f"full lmm() route {full}")
    for reason, n in reasons.items():
        print(f"  skipped/partial ({n}): {reason}")
    lines = [f"{'scenario':20} {'stratum':14} {'objective':>9} {'crit':>9} {'theta':>9} {'beta':>9} {'df':>9} sing"]
    for case in CASES:
        r = routes[case]
        if not r.objective:
            continue
        ref = reference(case)
        try:
            reml = model(case, True)
            obj = max(rel(reml.deviance(float(as_list(p["theta"])[0])), p["reml"], 1.0) for p in ref["probes"])
            ours = our_fit(case)
            crit = -2.0 * ours.loglik - ref["reml_criterion"]
            theta = abs(ours.theta - float(ref["theta"][0]))
            beta = df = np.nan
            if r.lmm is not None:
                rec = fit(case)
                coefs = {c["name"]: c for c in rec["details"]["coefficients"]}
                scale = _scale(case)
                beta = max((rel(coefs[x["name"]]["estimate"], x["estimate"], scale) for x in ref["fixed"]
                            if x["name"] in coefs), default=np.nan)
                df = max((rel(coefs[x["name"]]["df"], x["df"], 1.0) for x in ref["fixed"] if x["name"] in coefs
                          and coefs[x["name"]]["df"] is not None and x["df"] is not None), default=np.nan)
        except Exception as exc:  # the parametrized tests report it properly
            lines.append(f"{case:20} ERROR {exc}")
            continue
        lines.append(f"{case:20} {ref['scenario']['stratum']:14} {obj:9.1e} {crit:+9.1e} {theta:9.1e} "
                     f"{beta:9.1e} {df:9.1e} {'R' if ref['singular'] else '-'}")
    print("(objective: worst relative REML error over the probes; crit: ours - lme4, negative = csv-stats better)")
    print("\n".join(lines))
