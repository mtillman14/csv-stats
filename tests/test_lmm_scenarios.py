@pytest.mark.parametrize("case", CASES)
def test_covariate_grid_value_matches_emmeans(case):
    """csv-stats' reference-grid value per covariate (its mean over the
    fitted rows) is emmeans' ref_grid value."""
    ref = _need_contrasts(case)
    theirs = as_dict(ref.get("covariates_at"))
    if not ref["covariates"]:
        pytest.skip("no covariates")
    assert theirs, "the fixture predates covariates_at: rerun make_lmm_scenarios.R"
    ours = pairwise(case, ref["factors"][0])["details"]["covariates_at"]
    for c, v in theirs.items():
        (value,) = as_list(v)
        assert ours[c]["source"] == "mean"
        assert ours[c]["value"] == pytest.approx(value, rel=1e-12, abs=1e-12), c


# --- the table ------------------------------------------------------------------

def test_print_parity_table():
    """Not an assertion: what csv-stats can check today, and the worst error
    per scenario (run with -s)."""
    if not CASES:
        print("\nno sampled scenarios: run tests/reference/make_lmm_scenarios.R")
        return
    routes = {c: _route(c) for c in CASES}
    print(f"\nLMM scenario parity vs lme4: {len(CASES)} scenarios; "
          f"objective {sum(r.objective for r in routes.values())}; "
          f"lmm() {sum(r.lmm is not None for r in routes.values())}; "
          f"term tests {sum(r.terms for r in routes.values())}; "
          f"contrasts {sum(r.contrasts for r in routes.values())}")
    reasons = pd.Series([r.reason for r in routes.values() if r.reason]).value_counts()
    for reason, n in reasons.items():
        print(f"  partial ({n}): {reason}")
    lines = [f"{'scenario':20} {'stratum':14} {'objective':>9} {'crit':>9} {'theta':>9} {'beta':>9} {'df':>9} "
             f"sing path"]
    for case in CASES:
        r = routes[case]
        if not r.objective:
            continue
        ref = reference(case)
        try:
            reml = model(case, True)
            obj = max(rel(reml.deviance(to_ours(case, p["theta"])), p["reml"], 1.0) for p in ref["probes"])
            ours = our_fit(case)
            crit = ours.criterion - ref["reml_criterion"]
            theta = float(np.max(np.abs(np.asarray(ours.theta) - to_ours(case, ref["theta"]))))
            beta = df = np.nan
            if r.lmm is not None:
                rec = fit(case)
                coefs = {c["name"]: c for c in rec["details"]["coefficients"]}
                scale = _scale(case)
                beta = max((rel(coefs[x["name"]]["estimate"], x["estimate"], scale) for x in ref["fixed"]
                            if x["name"] in coefs), default=np.nan)
                df = max((rel(coefs[x["name"]]["df"], x["df"], 1.0) for x in ref["fixed"] if x["name"] in coefs
                          and coefs[x["name"]]["df"] is not None and x["df"] is not None), default=np.nan)
        except Exception as exc:  # the parametrized tests report it properly
            lines.append(f"{case:20} ERROR {type(exc).__name__}: {exc}")
            continue
        lines.append(f"{case:20} {ref['scenario']['stratum']:14} {obj:9.1e} {crit:+9.1e} {theta:9.1e} "
                     f"{beta:9.1e} {df:9.1e} {'R' if ref['singular'] else '-'}    {ours.optimizer_path}")
    print("(objective: worst relative REML error over the probes; crit: ours - lme4, negative = csv-stats better)")
    print("\n".join(lines))
