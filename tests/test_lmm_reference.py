"""csvstats.lmm against R (lme4 / lmerTest), scenario by scenario.

Stage 2 of .claude/plan-lmm-satterthwaite.md: FIT PARITY. Satterthwaite
degrees of freedom are computed from the fitted model, so they can only match
lmerTest if the fit itself matches lme4: the fixed effects, their standard
errors, the variance components and the REML log-likelihood. This file
checks that, for every dataset in tests/reference (generated by
make_lmm_reference.R), before any df work.

Run with ``-s`` to see the parity table: the largest relative error per
scenario, so accuracy is visible, not just pass/fail.
"""

from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path

import numpy as np
import pandas as pd
import pytest

from csvstats.lmm import lmm

REF = Path(__file__).parent / "reference"
CASES = sorted(p.stem for p in (REF / "results").glob("*.json"))

# Tolerances. Fixed effects and SEs are scaled by the data's SD, so the
# datasets around 1e-3 and 1e4 are held to the same relative standard.
EST_RTOL = 1e-5
SE_RTOL = 1e-4
VAR_RTOL = 1e-3
LOGLIK_ATOL = 1e-3
# A singular fit sits on a boundary; two optimizers approach it differently.
SINGULAR_LOOSEN = 100


def _as_list(value) -> list:
    """jsonlite's auto_unbox wrote a one-factor list as a bare string and an
    empty one as null (fixtures of 2026-10-19); a list either way here."""
    if value is None:
        return []
    return [value] if isinstance(value, str) else list(value)


@lru_cache(maxsize=None)
def reference(case: str) -> dict:
    with open(REF / "results" / f"{case}.json") as f:
        ref = json.load(f)
    for key in ("factors", "between", "within"):
        ref[key] = _as_list(ref.get(key))
    return ref


@lru_cache(maxsize=None)
def data(case: str) -> pd.DataFrame:
    ref = reference(case)
    return pd.read_csv(REF / "datasets" / f"{case}.csv", dtype={f: str for f in ["subject", *ref["factors"]]})


@lru_cache(maxsize=None)
def fit(case: str) -> dict:
    ref = reference(case)
    return lmm(data(case), "y", between=ref["between"], within=ref["within"], subject="subject",
               levels=ref["levels"])


def _skip_reason(case: str) -> str | None:
    ref = reference(case)
    if ref["scenario"].get("future"):
        return "random slopes: future scope (csv-stats fits intercept-only models)"
    if ref.get("error"):
        return f"R could not fit it: {ref['error']}"
    return None


def _usable(case: str) -> dict:
    reason = _skip_reason(case)
    if reason:
        pytest.skip(reason)
    return reference(case)


def _scale(case: str) -> float:
    return float(data(case)["y"].std())


def _loosen(ref: dict) -> float:
    return SINGULAR_LOOSEN if ref.get("singular") else 1.0


def _r_variances(ref: dict) -> tuple[float, float]:
    rows = ref["varcorr"]
    subject = next(r["vcov"] for r in rows if r["grp"] == "subject" and r["var1"] == "(Intercept)" and r["var2"] is None)
    residual = next(r["vcov"] for r in rows if r["grp"] == "Residual")
    return subject, residual


def test_the_reference_set_is_present():
    """Every results file has its dataset, and there are enough to matter."""
    assert len(CASES) >= 70, "run tests/reference/make_lmm_reference.R"
    for case in CASES:
        assert (REF / "datasets" / f"{case}.csv").exists(), case


@pytest.mark.parametrize("case", CASES)
def test_fixed_effects_match_lme4(case):
    ref = _usable(case)
    ours = {c["name"]: c for c in fit(case)["details"]["coefficients"]}
    assert set(ours) == {r["name"] for r in ref["fixed"]}, "same model terms and coding (contr.sum)"
    scale = _scale(case)
    loosen = _loosen(ref)
    for r in ref["fixed"]:
        mine = ours[r["name"]]
        assert mine["estimate"] == pytest.approx(r["estimate"], rel=EST_RTOL * loosen, abs=EST_RTOL * loosen * scale), \
            f"{r['name']} estimate"
        assert mine["se"] == pytest.approx(r["se"], rel=SE_RTOL * loosen, abs=SE_RTOL * loosen * scale), \
            f"{r['name']} SE"


@pytest.mark.parametrize("case", CASES)
def test_variance_components_match_lme4(case):
    ref = _usable(case)
    subject, residual = _r_variances(ref)
    details = fit(case)["details"]
    var = _scale(case) ** 2
    loosen = _loosen(ref)
    assert details["residual_variance"] == pytest.approx(residual, rel=VAR_RTOL * loosen)
    assert details["subject_intercept_variance"] == pytest.approx(
        subject, rel=VAR_RTOL * loosen, abs=VAR_RTOL * loosen * var)


@pytest.mark.parametrize("case", CASES)
def test_singular_fits_are_flagged_like_lme4(case):
    """lme4's isSingular and csv-stats' singular_fit warning agree, both ways."""
    ref = _usable(case)
    flagged = any(w["code"] == "singular_fit" for w in fit(case)["warnings"])
    assert flagged == bool(ref["singular"]), "lme4 singular" if ref["singular"] else "lme4 NOT singular"


@pytest.mark.parametrize("case", CASES)
def test_reml_log_likelihood_matches_lme4(case):
    ref = _usable(case)
    ours = fit(case)["details"]["log_likelihood"]
    assert ours == pytest.approx(ref["loglik_reml"], abs=LOGLIK_ATOL * _loosen(ref))


def lme4_stopped_short(case: str) -> bool:
    """csv-stats' REML log-likelihood is HIGHER than lme4's: lme4's optimizer
    stopped before the optimum, so its estimates (and everything computed
    from them) carry that error. W3rep_mcar15 (2026-10-19): loglik 1e-8
    apart, SEs 4e-6, so the intercept's t = 50.4 differed by 2.4e-5.
    Tolerances are relaxed ONLY for such datasets, never across the board."""
    better = fit(case)["details"]["log_likelihood"] - reference(case)["loglik_reml"]
    return better > 1e-10


def test_lme4_stopping_short_is_rare():
    """The relaxation must stay an exception: if it spreads, csv-stats (not
    lme4) is probably the one that changed."""
    usable = [c for c in CASES if not _skip_reason(c)]
    short = [c for c in usable if lme4_stopped_short(c)]
    assert len(short) <= 3, short


DF_RTOL = 1e-3
T_RTOL = 1e-5
P_ATOL = 1e-4


@pytest.mark.parametrize("case", CASES)
def test_coefficient_satterthwaite_matches_lmertest(case):
    """Stage 3: every coefficient's Satterthwaite df, t and p (lmerTest's
    summary()). A fallback to Wald is allowed only with its warning, and
    then the comparison is skipped for that coefficient, never silent."""
    ref = _usable(case)
    rec = fit(case)
    ours = {c["name"]: c for c in rec["details"]["coefficients"]}
    if any(c["df_method"] != "satterthwaite" for c in ours.values()):
        assert any(w["code"] == "satterthwaite_unavailable" for w in rec["warnings"])
    # A fallback is a failure only where lmerTest itself produced a df.
    fallbacks = [r["name"] for r in ref["fixed"]
                 if r["df"] is not None and ours[r["name"]]["df_method"] != "satterthwaite"]
    loosen = 10.0 if ref.get("singular") or lme4_stopped_short(case) else 1.0
    for r in ref["fixed"]:
        mine = ours[r["name"]]
        if mine["df_method"] != "satterthwaite" or r["df"] is None:
            continue
        assert mine["df"] == pytest.approx(r["df"], rel=DF_RTOL * loosen), f"{r['name']} df"
        assert mine["t"] == pytest.approx(r["t"], rel=T_RTOL * loosen, abs=1e-8), f"{r['name']} t"
        assert mine["p"] == pytest.approx(r["p"], abs=P_ATOL * loosen), f"{r['name']} p"
    assert not fallbacks, f"Wald fallback where lmerTest has a df: {fallbacks}"


def _rel(a, b, floor):
    return abs(a - b) / max(abs(b), floor)


def test_print_parity_table():
    """Not an assertion: the largest relative error per scenario (run with -s)."""
    lines = [f"{'scenario':58} {'beta':>9} {'se':>9} {'var_s':>9} {'var_e':>9} {'loglik':>9} {'df':>9} sing"]
    for case in CASES:
        if _skip_reason(case):
            continue
        ref = reference(case)
        try:
            rec = fit(case)
        except Exception as exc:  # the parametrized tests report it properly
            lines.append(f"{case:58} ERROR {exc}")
            continue
        scale = _scale(case)
        ours = {c["name"]: c for c in rec["details"]["coefficients"]}
        beta = max((_rel(ours[r["name"]]["estimate"], r["estimate"], scale) for r in ref["fixed"] if r["name"] in ours),
                   default=np.nan)
        se = max((_rel(ours[r["name"]]["se"], r["se"], scale) for r in ref["fixed"] if r["name"] in ours), default=np.nan)
        subject, residual = _r_variances(ref)
        var_s = _rel(rec["details"]["subject_intercept_variance"], subject, scale ** 2)
        var_e = _rel(rec["details"]["residual_variance"], residual, scale ** 2)
        loglik = abs(rec["details"]["log_likelihood"] - ref["loglik_reml"])
        flagged = any(w["code"] == "singular_fit" for w in rec["warnings"])
        df = max((_rel(ours[r["name"]]["df"], r["df"], 1.0) for r in ref["fixed"]
                  if r["name"] in ours and ours[r["name"]]["df"] is not None and r["df"] is not None), default=np.nan)
        lines.append(f"{case:58} {beta:9.1e} {se:9.1e} {var_s:9.1e} {var_e:9.1e} {loglik:9.1e} {df:9.1e} "
                     f"{'R' if ref['singular'] else '-'}{'P' if flagged else '-'}")
    print("\nLMM fit parity vs lme4 (relative error; sing: R = lme4 singular, P = csv-stats flagged)")
    print("\n".join(lines))
